/**
 * Точка запуску gateway-сервера.
 *
 * Призначення:
 * - завантажити змінні середовища з .env;
 * - підключити основний Express-застосунок;
 * - визначити порт запуску;
 * - запустити HTTP-сервер шлюзу.
 */

require("dotenv").config();

const app = require("./app");

/**
 * Порт, на якому буде працювати gateway.
 *
 * Якщо змінна PORT задана в середовищі або у файлі .env,
 * використовується її значення.
 * Інакше за замовчуванням використовується порт 8080.
 *
 * @type {string|number}
 */
const PORT = process.env.PORT || 8080;

/**
 * Запуск HTTP-сервера шлюзу.
 *
 * Після успішного старту в консоль виводиться повідомлення
 * з інформацією про порт, на якому працює застосунок.
 */
app.listen(PORT, () => {
  console.log(`Gateway running on port ${PORT}`);
});